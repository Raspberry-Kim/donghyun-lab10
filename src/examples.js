/* 정수 n을 동현랭 식으로. 붙여 쓴 원자는 더하고 띄어 쓴 항은 곱한다. 10 이하는 글자 하나, 그 위는 약수로 쪼개고, 소수는 10을 여러 번 붙여 더한다 */
function expression(n){
  if(n===0)return '도옹ㅠ';
  if(n<0)return 'ㅠ '+expression(-n);
  if(n<=10)return '도'+'오'.repeat(n-1)+'옹';
  for(let a=10;a>=2;a--)if(n%a===0)return expression(a)+' '+expression(n/a);
  return expression(10).repeat(Math.floor(n/10))+(n%10?expression(n%10):'');
}
